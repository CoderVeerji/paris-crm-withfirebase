// DRY RUN — prod leads ka `state` field padhta hai (sirf state select, kuch likhta nahi), dikhata hai kya badlega.
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
const admin = require('firebase-admin');
const { normalizeState, setStateConfig, resolveState } = await import('../app/src/lib/states.js');
admin.initializeApp({ projectId: 'paris-crm' });
const db = admin.firestore();
const cfg = (await db.doc('config/settings').get()).data() || {};
setStateConfig(cfg.State_List, cfg.State_Aliases);
console.log('State_List items:', String(cfg.State_List || '').split(',').filter((x) => x.trim()).length, '| aliases:', cfg.State_Aliases ? 'yes' : 'none');
const snap = await db.collection('leads').select('state').get();
console.log('leads scanned', snap.size);
const counts = {}; const changes = [];
snap.forEach((d) => {
  const s = d.get('state') || '';
  counts[s] = (counts[s] || 0) + 1;
  const n = normalizeState(s);
  if (s && n !== s) changes.push({ id: d.id, from: s, to: n, ok: resolveState(s) === n });
});
const byPair = {};
changes.forEach((c) => { const k = `${c.from} -> ${c.to}${c.ok ? '' : ' (UNMATCHED)'}`; byPair[k] = (byPair[k] || 0) + 1; });
console.log('\nWILL CHANGE', changes.length, 'leads:');
Object.entries(byPair).sort((a, b) => b[1] - a[1]).forEach(([k, n]) => console.log(String(n).padStart(5), k));
const list = new Set(String(cfg.State_List || '').split(',').map((x) => x.trim()).filter(Boolean));
const outside = Object.entries(counts).filter(([s]) => s && !list.has(s) && normalizeState(s) === s).sort((a, b) => b[1] - a[1]);
console.log('\nNOT in State_List and not auto-fixable (left as is):', outside.length, 'distinct,', outside.reduce((a, [, n]) => a + n, 0), 'leads');
outside.slice(0, 40).forEach(([s, n]) => console.log(String(n).padStart(5), JSON.stringify(s)));
fs.mkdirSync('reports', { recursive: true });
fs.writeFileSync('reports/state-fix-plan.json', JSON.stringify(changes.filter((c) => c.ok), null, 1));
console.log('\nplan saved: migration/reports/state-fix-plan.json (git-ignored)');
process.exit(0);
